"""Dependabot CLI jobs: build the job of an item, run it, read what it produced."""

from __future__ import annotations

import json
import os
import posixpath
import subprocess
import tempfile
import time
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import apply_codes as codes

TOKEN_ENV = "LOCAL_GITHUB_ACCESS_TOKEN"
MANIFESTS = {
    "package-lock.json",
    "npm-shrinkwrap.json",
    "package.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "poetry.lock",
    "pyproject.toml",
    "Pipfile.lock",
    "uv.lock",
    "build.gradle",
    "build.gradle.kts",
    "pom.xml",
}
# Written by the scan, never in the repository: it stands for the build file of its
# directory (or of the nearest directory above that has one)
GENERATED_LOCKFILE = "gradle.lockfile"
GRADLE_BUILD_FILES = ("build.gradle", "build.gradle.kts")
JOB_TIMEOUT = 3600
TIMEOUT = codes.DEPENDABOT_TIMEOUT  # the error of a job that hit its time limit


class JobError(RuntimeError):
    """The CLI did not give a usable answer."""


@dataclass(frozen=True)
class Settings:
    """The CLI and the images it starts, all pinned by the caller."""

    binary: str
    updater_images: Mapping[str, str]
    proxy_image: str
    token: str = field(default="", repr=False)
    timeout: int = JOB_TIMEOUT


@dataclass
class Outcome:
    """The result of one job: the change events, or why there are none."""

    files: list[dict[str, Any]] = field(default_factory=list)
    dependencies: list[dict[str, Any]] = field(default_factory=list)
    error: str | None = None
    seconds: int = 0


def is_manifest(tree: Path, location: str) -> bool:
    parts = location.split("/")
    if "node_modules" in parts:
        return False
    name = parts[-1]
    if name == GENERATED_LOCKFILE:
        return True
    listed = name in MANIFESTS or (
        name.startswith("requirements") and name.endswith(".txt")
    )
    return listed and (tree / location).is_file()


def build_file_dir(tree: Path, directory: str) -> str | None:
    """The nearest directory, from ``directory`` up to the root, with a build file."""
    current = directory
    while True:
        if any((tree / current / name).is_file() for name in GRADLE_BUILD_FILES):
            return current
        if current in ("", "."):
            return None
        current = posixpath.dirname(current)


def job_directories(tree: Path, item: Mapping[str, Any]) -> tuple[str, list[str]]:
    """The package manager of an item and the directories its job covers.

    The directories are those of the item's manifest and lockfile locations (image
    paths and files of ``node_modules`` do not count); a root file is ``/``. For
    Maven packages a build file at or above the directory makes it Gradle, and the
    report's ``gradle.lockfile`` locations are generated by the scan, so each stands
    for the build file of its directory or of the nearest one above it.
    """
    ecosystem = item["ecosystem"]
    dirs = sorted(
        {posixpath.dirname(loc) for loc in item["locations"] if is_manifest(tree, loc)}
    ) or [""]
    if ecosystem == "npm":
        manager = "npm_and_yarn"
    elif ecosystem == "PyPI":
        manager = "pip"
    elif ecosystem == "Maven":
        mapped = [build_file_dir(tree, d) for d in dirs]
        manager = "gradle" if any(d is not None for d in mapped) else "maven"
        if manager == "gradle":
            dirs = sorted({d for d in mapped if d is not None})
    else:
        raise JobError(f"ecosystem {ecosystem} not supported")
    return manager, ["/" + d if d else "/" for d in dirs]


def source(repo: str, branch: str, directories: Sequence[str]) -> dict[str, Any]:
    return {
        "provider": "github",
        "repo": repo,
        "directories": list(directories),
        "branch": branch,
    }


def security_job(
    item: Mapping[str, Any],
    manager: str,
    repo: str,
    branch: str,
    directories: Sequence[str],
) -> dict[str, Any]:
    """A security update job for one package. The advisory is the one the plan
    stands on: every version below the target is affected, the target and above is
    patched (no advisory lookup, the plan already compared the versions).
    """
    targets = sorted({t["target"] for t in item["targets"] if t["target"]})
    return {
        "package-manager": manager,
        "source": source(repo, branch, directories),
        "security-updates-only": True,
        "dependencies": [item["pkg"]],
        "allowed-updates": [{"dependency-type": "all"}],
        "security-advisories": [
            {
                "dependency-name": item["pkg"],
                "affected-versions": [f"< {t}"],
                "patched-versions": [f">= {t}"],
            }
            for t in targets
        ],
    }


def docker_job(repo: str, branch: str, directories: Sequence[str]) -> dict[str, Any]:
    """A version update job over every Dockerfile directory; another major version
    of a base image is never proposed.
    """
    return {
        "package-manager": "docker",
        "source": source(repo, branch, directories),
        "allowed-updates": [{"dependency-type": "all"}],
        "ignore-conditions": [
            {"dependency-name": "*", "update-types": ["version-update:semver-major"]}
        ],
    }


def read_events(document: Mapping[str, Any]) -> Outcome:
    """The change and the error of a smoke test file: the files of every
    ``create_pull_request`` event, or the first error, or nothing.
    """
    outcome = Outcome()
    errors: list[str] = []
    for event in document.get("output") or []:
        data = (event.get("expect") or {}).get("data") or {}
        if event["type"] == "create_pull_request":
            outcome.files.extend(data.get("updated-dependency-files") or [])
            outcome.dependencies.extend(data.get("dependencies") or [])
        elif event["type"] == "record_update_job_error":
            errors.append(str(data.get("error-type")))
    if errors:
        outcome.error = errors[0]
    return outcome


def remove_containers(*images: str) -> None:
    """Stop what a killed CLI left running: the updater and proxy containers."""
    filters = [x for image in images for x in ("--filter", f"ancestor={image}")]
    ids = subprocess.run(
        ["docker", "ps", "-aq", *filters], capture_output=True, check=False, text=True
    ).stdout.split()
    if ids:
        subprocess.run(["docker", "rm", "-f", *ids], capture_output=True, check=False)
    subprocess.run(
        ["docker", "network", "prune", "-f"], capture_output=True, check=False
    )


def run_job(
    job: Mapping[str, Any], tree: Path, settings: Settings, manager: str
) -> Outcome:
    """Run one update job against ``tree``. The tree is not changed; the files the
    job would change come back in the outcome.
    """
    image = settings.updater_images.get(manager)
    if image is None:
        raise JobError(f"no updater image for {manager}")
    credentials = [
        {
            "type": "git_source",
            "host": "github.com",
            "username": "x-access-token",
            "password": f"${TOKEN_ENV}",
        }
    ]
    with tempfile.TemporaryDirectory() as work:
        job_file, out_file = Path(work) / "job.json", Path(work) / "out.yaml"
        job_file.write_text(
            json.dumps({"job": job, "credentials": credentials}), encoding="utf-8"
        )
        started = time.monotonic()
        command = [
            settings.binary,
            "update",
            "-f",
            str(job_file),
            "-o",
            str(out_file),
            "--local",
            str(tree),
            "--updater-image",
            image,
            "--proxy-image",
            settings.proxy_image,
        ]
        try:
            done = subprocess.run(
                command,
                env={**os.environ, TOKEN_ENV: settings.token},
                capture_output=True,
                check=False,
                text=True,
                timeout=settings.timeout,
            )
        except subprocess.TimeoutExpired:
            remove_containers(image, settings.proxy_image)
            return Outcome(error=TIMEOUT, seconds=round(time.monotonic() - started))
        seconds = round(time.monotonic() - started)
        if not out_file.is_file():
            tail = (done.stderr or done.stdout).strip()[-500:]
            return Outcome(
                error=f"dependabot failed (exit {done.returncode}): {tail}",
                seconds=seconds,
            )
        converted = subprocess.run(
            ["yq", "-o=json", ".", str(out_file)],
            capture_output=True,
            check=False,
            text=True,
        )
        if converted.returncode != 0:
            raise JobError(
                f"cannot read the job output: {converted.stderr.strip()[-300:]}"
            )
        outcome = read_events(json.loads(converted.stdout))
        outcome.seconds = seconds
        return outcome
