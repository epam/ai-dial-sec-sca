POETRY_LOCK = "poetry.lock"
POETRY_HEADER = re.compile(r"@generated by Poetry (\S+)")
NOT_NEEDED = "security_update_not_needed"
NO_CHANGE = "dependabot produced no change"
# the Dependabot error types that mean "cannot make this change"
REFUSALS = {"security_update_not_possible", "security_update_dependency_not_found"}
# What Dependabot says when it cannot make the change: the npm items go on to the
# override step. "Not needed" counts when the detector still finds the item; a failed
# rescan does not count.
FALLBACK_ON = {*REFUSALS, NOT_NEEDED, NO_CHANGE, TIMEOUT}


@dataclass
class Kept:
    """What the line has kept so far: the detector result after each kept change, from
    the baseline on, with the package of the change; and the items applied (by a
    change of their own or with one of another item), whose records must stay gone.
    """

    steps: list[tuple[str, set[Finding]]]
    held: list[Mapping[str, Any]]

    def keep(self, item: Mapping[str, Any], after: set[Finding]) -> None:
        self.steps.append((item["pkg"], after))
        self.held.append(item)

    def reintroduced(self, after: set[Finding]) -> str | None:
        """The package of the first earlier applied item that has records in ``after``."""
        return next((i["pkg"] for i in self.held if present(i, after)), None)


@dataclass(frozen=True)
class Tools:
    """What the line needs from the outside, so the flow can be tested without the
    CLI, Trivy and Docker.
    """

    dependabot: Callable[[Mapping[str, Any], str], Outcome]
    scan_tree: Callable[[], set[Finding]]
    scan_image: Callable[[Path, str], set[Finding]]
    npm_install: Callable[[], str | None]
    npm_ls: Callable[[str], list[tuple[str, str]]]
    npm_version: Callable[[], str]
    tool_versions: Callable[[], dict[str, str | None]]


def dockerfiles(tree: Path) -> list[str]:
    return sorted(
        p.relative_to(tree).as_posix()
        for p in tree.rglob("Dockerfile*")
        if p.is_file() and "node_modules" not in p.parts and ".git" not in p.parts
    )


def changes(
    outcome: Outcome, directories: set[str] | None = None
) -> list[dict[str, Any]]:
    """The dependency changes of a job; with ``directories`` only those of the
    given job directories (the ones whose files were kept).
    """
    return [
        {
            "name": d.get("name"),
            "from": d.get("previous-version"),
            "to": d.get("version"),
            "directory": d.get("directory"),
        }
        for d in outcome.dependencies
        if directories is None or str(d.get("directory")).strip("/") in directories
    ]


def dependabot_result(detail: str) -> str:
    """What Dependabot said, as a code: the error type as given (``security_update_*``)
    or an apply code.
    """
    if detail.startswith("security_update_"):
        return detail
    return {NO_CHANGE: codes.DEPENDABOT_NO_CHANGE, TIMEOUT: TIMEOUT}.get(
        detail, codes.DEPENDABOT_FAILED
    )


def dependabot_code(detail: str) -> str:
    """The reason code of a Dependabot outcome without a change: ``detail`` is its
    error type or text.
    """
    if detail == NO_CHANGE:
        return codes.DEPENDABOT_NO_CHANGE
    if detail in REFUSALS:
        return codes.DEPENDABOT_REFUSED
    if detail == TIMEOUT:
        return codes.DEPENDABOT_TIMEOUT
    return codes.DEPENDABOT_FAILED


def new_record(item: Mapping[str, Any]) -> dict[str, Any]:
    return {
        "pkg": item["pkg"],
        "class": item["class"],
        "ecosystem": item["ecosystem"],
        "method": item["method"],
        "installed": [t["installed"] for t in item["targets"]],
        "planned": [t["target"] for t in item["targets"]],
        "vulns": [v["id"] for v in item["vulns"]],
        "severities": sorted({v["severity"] for v in item["vulns"]}),
        "status": "manual",
        "reverted": False,
        "reason": item["reason"],
        "reason_code": item["reason_code"],
        "files": [],
        "changes": [],
        "seconds": 0,
    }


def reverted(
    record: dict[str, Any], journal: Journal, checkpoint: Mapping[str, bytes | None]
) -> None:
    """Put the files back: the item's own change is gone from the tree and the record."""
    journal.restore(checkpoint)
    record.update(reverted=True, changes=[], files=[], left_out=0)


def fail(record: dict[str, Any], reason: str, code: str) -> dict[str, Any]:
    """The item stays a recommendation (an npm item may still go to the override
    step, which looks at the detail).
    """
    record["detail"] = record["reason"] = reason
    record["reason_code"] = code
    return record


def already_fixed(record: dict[str, Any], why: str) -> dict[str, Any]:
    """Nothing to apply: the branch no longer has the vulnerabilities."""
    record.update(
        status="already_fixed",
        detail=why,
        reason=f"already fixed on the branch ({why})",
        reason_code=codes.NOT_IN_BASELINE,
    )
    return record


def fixed_with(
    record: dict[str, Any], item: Mapping[str, Any], kept: Kept
) -> dict[str, Any]:
    """The item's vulnerabilities went with kept changes of this line: applied
    without a change of its own, ``fixed_with`` names the packages of the changes
    after which its records were gone.
    """
    names = [
        pkg
        for (_, was), (pkg, now) in zip(kept.steps, kept.steps[1:])
        if present(item, was) and not present(item, now)
    ]
    record.update(
        status="applied",
        reason=None,
        reason_code=None,
        files=[],
        changes=[],
        fixed_with=list(dict.fromkeys(names)),
    )
    kept.held.append(item)
    return record


def settle(
    record: dict[str, Any],
    item: Mapping[str, Any],
    baseline: set[Finding],
    current: set[Finding],
    kept: Kept,
) -> dict[str, Any] | None:
    """Rules 1a and 1b before any change: the record of an item whose vulnerabilities
    are gone from the baseline (already fixed) or from the tree a kept change left
    (fixed with it), else None.
    """
    verdict = gate(item, current, current, baseline)
    if verdict and verdict[0] == codes.NOT_IN_BASELINE:
        return already_fixed(record, verdict[1])
    if verdict and verdict[0] == EARLIER:
        return fixed_with(record, item, kept)
    return None


def judge(
    item: Mapping[str, Any],
    record: dict[str, Any],
    journal: Journal,
    checkpoint: Mapping[str, bytes | None],
    baseline: set[Finding],
    current: set[Finding],
    after: set[Finding],
    kept: Kept,
) -> dict[str, Any] | None:
    """The rescan gate of a change (rules 2, 3, 3b): None when it proves the item and
    no earlier applied item has its records back, else the change is reverted and the
    record says why.
    """
    verdict = gate(item, current, after, baseline)
    if verdict:
        reverted(record, journal, checkpoint)
        return fail(record, f"rescan gate: {verdict[1]}", verdict[0])
    back = kept.reintroduced(after)
    if back:
        reverted(record, journal, checkpoint)
        return fail(
            record,
            f"rescan gate: the change brings back the records of {back}",
            codes.GATE_REINTRODUCED,
        )
    return None


def apply_security(
    item: Mapping[str, Any],
    repo: str,
    branch: str,
    journal: Journal,
    tools: Tools,
    baseline: set[Finding],
    current: set[Finding],
    kept: Kept,
) -> tuple[dict[str, Any], set[Finding]]:
    record = new_record(item)
    settled = settle(record, item, baseline, current, kept)
    if settled:
        return settled, current
    try:
        manager, directories = job_directories(journal.tree, item)
    except JobError as exc:
        return fail(record, str(exc), codes.ECOSYSTEM_UNSUPPORTED), current
    record["package_manager"], record["directories"] = manager, directories
    try:
        outcome = tools.dependabot(
            security_job(item, manager, repo, branch, directories), manager
        )
    except JobError as exc:
        return fail(record, str(exc), codes.DEPENDABOT_FAILED), current
    record["seconds"] = outcome.seconds
    checkpoint = journal.checkpoint()
    changed, left_out = journal.apply(outcome.files)
    if not changed:
        if outcome.error == NOT_NEEDED:
            # Dependabot's word is not enough: the detector still finds the item
            return fail(record, NOT_NEEDED, codes.DEPENDABOT_REFUSED), current
        detail = outcome.error or NO_CHANGE
        return fail(record, detail, dependabot_code(detail)), current
    record["changes"], record["left_out"] = changes(outcome), left_out
    try:
        after = tools.scan_tree()
    except ScanError as exc:
        reverted(record, journal, checkpoint)
        return fail(record, f"rescan failed: {exc}", codes.RESCAN_FAILED), current
    refused = judge(item, record, journal, checkpoint, baseline, current, after, kept)
    if refused:
        return refused, current
    record.update(status="applied", reason=None, reason_code=None, files=changed)
    kept.keep(item, after)
    return record, after


def resolved_changes(
    pkg: str, pairs: Sequence[tuple[str, str]], copies: Sequence[tuple[str, str]]
) -> list[dict[str, Any]]:
    """What the override did to the package: for each installed version the versions
    of the target's line that npm resolved (any line when the target's has none).
    """
    out = []
    for installed, target in pairs:
        versions = {v for _, v in copies if same_line(v, target)} or {
            v for _, v in copies
        }
        out += [
            {"name": pkg, "from": installed, "to": v, "directory": "/"}
            for v in sorted(versions, key=numbers)
        ]
    return out


def apply_override(
    item: Mapping[str, Any],
    record: dict[str, Any],
    journal: Journal,
    tools: Tools,
    baseline: set[Finding],
    current: set[Finding],
    node: tuple[str, str] | None,
    kept: Kept,
) -> tuple[dict[str, Any], set[Finding]]:
    """The npm-override step for an item Dependabot could not fix: overrides in the
    root ``package.json``, the lockfile updated by npm, the installed copies
    checked, then the rescan gate. Any failure puts the files back.
    """
    pkg, tree = item["pkg"], journal.tree
    said = record["detail"]
    record["dependabot_result"] = dependabot_result(said)
    record["dependabot_detail"] = None if said == record["dependabot_result"] else said
    settled = settle(record, item, baseline, current, kept)
    if settled:
        return settled, current

    def manual(reason: str, code: str) -> tuple[dict[str, Any], set[Finding]]:
        record["reason"], record["reason_code"] = reason, code
        return record, current

    def revert(reason: str, code: str) -> tuple[dict[str, Any], set[Finding]]:
        reverted(record, journal, checkpoint)
        return manual(reason, code)

    def read(name: str) -> str:
        return (tree / name).read_bytes().decode("utf-8")

    if item["relationship"] == "direct":
        return manual(
            "direct dependency: an override would conflict with its spec",
            codes.OVERRIDE_DIRECT,
        )
    if item["relationship"] != "indirect":
        return manual(
            "the plan does not say whether the dependency is direct",
            codes.OVERRIDE_RELATIONSHIP_UNKNOWN,
        )
    if (
        LOCKFILE not in item["locations"]
        or not (tree / "package.json").is_file()
        or not (tree / LOCKFILE).is_file()
    ):
        return manual(
            "no package.json and package-lock.json at the root",
            codes.OVERRIDE_NO_ROOT_LOCKFILE,
        )
    if node is None:
        return manual("node version of the branch not found", codes.OVERRIDE_NO_NODE)
    record["node_version"], record["node_source"] = node
    pairs = [(t["installed"], t["target"]) for t in item["targets"] if t["target"]]
    checkpoint = journal.checkpoint()
    package, lock = read("package.json"), read(LOCKFILE)
    try:
        edited, record["override_keys"] = add_overrides(package, pkg, pairs)
    except (OverrideError, ValueError) as exc:
        return manual(str(exc), codes.OVERRIDE_NEEDS_MANUAL)
    journal.write("package.json", edited)
    journal.write(LOCKFILE, lock)
    record["npm_version"] = tools.npm_version()
    error = tools.npm_install()
    if error:
        return revert(error, codes.OVERRIDE_NPM_FAILED)
    after_lock = read(LOCKFILE)
    if lock_format(after_lock) != lock_format(lock):
        return revert(
            f"npm {record['npm_version']} would rewrite the lockfile format",
            codes.OVERRIDE_LOCKFILE_FORMAT,
        )
    try:
        copies = tools.npm_ls(pkg)
    except OverrideError as exc:
        return revert(str(exc), codes.OVERRIDE_NPM_FAILED)
    short = [
        path for path, version in copies if below_target(version, [t for _, t in pairs])
    ]
    if short:
        return revert(f"override did not reach {short[0]}", codes.OVERRIDE_NOT_REACHED)
    try:
        after = tools.scan_tree()
    except ScanError as exc:
        return revert(f"rescan failed: {exc}", codes.RESCAN_FAILED)
    refused = judge(item, record, journal, checkpoint, baseline, current, after, kept)
    if refused:
        return refused, current
    kept.keep(item, after)
    record.update(
        status="applied",
        reason=None,
        reason_code=None,
        detail=None,
        files=["package.json", LOCKFILE],
        changes=resolved_changes(pkg, pairs, copies),
        method_used="npm-override",
        changed_other=changed_other(lock, after_lock, pkg),
    )
    return record, after


def apply_docker(
    items: list[dict[str, Any]],
    repo: str,
    branch: str,
    journal: Journal,
    tools: Tools,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Bump the base images of the line once and let the image rescan decide per
    item. Returns the records of the items and the data of the step.
    """
    records = [new_record(i) for i in items]
    step: dict[str, Any] = {
        "status": "none",
        "changes": [],
        "files": [],
        "builds": [],
        "seconds": 0,
    }

    def all_manual(
        reason: str, code: str
    ) -> tuple[list[dict[str, Any]], dict[str, Any]]:
        for record in records:
            record["reason"], record["reason_code"] = reason, code
        return records, step

    files = dockerfiles(journal.tree)
    if not files:
        return all_manual("no Dockerfile in the tree", codes.NO_DOCKERFILE)
    parents = {Path(f).parent.as_posix() for f in files}
    directories = sorted("/" if p == "." else f"/{p}" for p in parents)
    outcome = tools.dependabot(docker_job(repo, branch, directories), "docker")
    step["seconds"] = outcome.seconds
    checkpoint = journal.checkpoint()
    changed, _ = journal.apply(outcome.files)
    if not changed:
        detail = outcome.error or NO_CHANGE
        return all_manual(detail, dependabot_code(detail))
    journal.restore(checkpoint)
    built = [p for p in changed if p in files]
    if not built:
        return all_manual(
            "dependabot changed no Dockerfile", codes.NO_DOCKERFILE_CHANGED
        )
    # only the built Dockerfiles are kept: a file the build does not cover is not proven
    kept_files = [f for f in outcome.files if event_path(f) in built]
    kept_dirs = {str(f["directory"]).strip("/") for f in kept_files}
    step["changes"], step["files"] = changes(outcome, kept_dirs), built

    def scan_all(label: str) -> set[Finding]:
        found: set[Finding] = set()
        for path in built:
            started = time.monotonic()
            try:
                found |= tools.scan_image(journal.tree, path)
            except ScanError as exc:
                raise type(exc)(f"{label} of {path}: {exc}") from exc
            finally:
                step["builds"].append(
                    {
                        "dockerfile": path,
                        "label": label,
                        "seconds": round(time.monotonic() - started),
                    }
                )
        return found

    try:
        before = scan_all("baseline build")
    except BuildError as exc:
        step["status"] = "none"
        return all_manual(f"image build failed: {exc}", codes.IMAGE_BUILD_FAILED)
    journal.apply(kept_files)
    try:
        after = scan_all("build after the bump")
    except ScanError as exc:
        journal.restore(checkpoint)
        step["status"] = "reverted"
        if isinstance(exc, BuildError):
            return all_manual(f"image build failed: {exc}", codes.IMAGE_BUILD_FAILED)
        return all_manual(f"rescan failed: {exc}", codes.RESCAN_FAILED)
    serious = new_serious(after, before)
    for record, item in zip(records, items, strict=True):
        if not present(item, before):
            # the item's records are in no built image: this bump cannot fix them
            record["reason"] = (
                "none of its records is in an image of a changed Dockerfile"
            )
            record["reason_code"] = codes.NO_DOCKERFILE_CHANGED
            continue
        verdict = (
            (
                codes.GATE_NEW_SERIOUS,
                f"new HIGH or CRITICAL after the bump: {', '.join(serious)}",
            )
            if serious
            else gate(item, before, after, before)
        )
        if verdict:
            record["reason"] = f"image rescan gate: {verdict[1]}"
            record["reason_code"] = verdict[0]
        else:
            record.update(
                status="applied",
                reason=None,
                reason_code=None,
                files=built,
                changes=step["changes"],
            )
    if any(r["status"] == "applied" for r in records):
        step["status"] = "applied"
    else:
        journal.restore(checkpoint)
        step["status"] = "reverted"
    return records, step


def lock_tools(journal: Journal) -> list[dict[str, str]]:
    """The poetry lockfiles of the tree that a different Poetry wrote than the one
    recorded in them: file, version recorded, version now.
    """
    out = []
    for path in journal.paths():
        before, after = journal.originals[path], journal.read(path)
        if Path(path).name != POETRY_LOCK or before is None or after is None:
            continue
        was, now = (
            POETRY_HEADER.search(data.decode("utf-8", "replace"))
            for data in (before, after)
        )
        if was and now and was[1] != now[1]:
            out.append({"file": path, "from": was[1], "to": now[1]})
    return out


def process_line(
    line: Mapping[str, Any], repo: str, tree: Path, tools: Tools
) -> dict[str, Any]:
    """Run the automated items of a plan line; the result says what was applied
    (and the files it changed) and what stays manual, with the reason.
    """
    started = time.monotonic()
    journal = Journal(tree)
    items = list(line["items"])
    security = [i for i in items if i["method"] == "dependabot"]
    baseline = tools.scan_tree() if security else set()
    current = baseline
    kept = Kept([("", baseline)], [])
    records: dict[int, dict[str, Any]] = {}
    for index, item in enumerate(items):
        if item["method"] == "dependabot":
            records[index], current = apply_security(
                item, repo, line["branch"], journal, tools, baseline, current, kept
            )
        elif item["method"] != "docker-tag":
            records[index] = new_record(item)
    due = [
        i
        for i, record in records.items()
        if items[i]["fallback"] == "npm-override"
        and record["status"] == "manual"
        and record.get("detail") in FALLBACK_ON
    ]
    node = detect_node(tree, dockerfiles(tree)) if due else None
    for i in due:
        records[i], current = apply_override(
            items[i], records[i], journal, tools, baseline, current, node, kept
        )
    docker = [
        (i, item) for i, item in enumerate(items) if item["method"] == "docker-tag"
    ]
    step: dict[str, Any] = {
        "status": "none",
        "changes": [],
        "files": [],
        "builds": [],
        "seconds": 0,
    }
    if docker:
        done, step = apply_docker(
            [item for _, item in docker], repo, line["branch"], journal, tools
        )
        records.update({i: record for (i, _), record in zip(docker, done, strict=True)})
    return {
        "line": line["line"],
        "ref": line["ref"],
        "branch": line["branch"],
        "baseline_findings": len(baseline),
        "detector": tools.tool_versions(),
        "items": [records[i] for i in sorted(records)],
        "docker": step,
        "files": journal.paths(),
        "lockfile_tools": lock_tools(journal),
        "seconds": round(time.monotonic() - started),
    }
